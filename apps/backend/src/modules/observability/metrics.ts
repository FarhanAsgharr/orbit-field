/**
 * Prometheus metrics.
 *
 * Hand-rolled rather than pulling in `prom-client`. The exposition format is
 * about sixty lines of text generation, and the alternative is a dependency
 * whose default metrics registry has global mutable state that behaves badly
 * under test isolation.
 *
 * What is measured is chosen from what actually pages someone at 3am: sync
 * throughput, conflict rate, upload failures, and request latency. Vanity
 * counters are omitted — every series costs cardinality in the scrape.
 */

import { prisma } from '../../db/prisma.js';

type Labels = Record<string, string>;

interface CounterState {
  help: string;
  type: 'counter' | 'gauge';
  values: Map<string, { labels: Labels; value: number }>;
}

interface HistogramState {
  help: string;
  buckets: number[];
  series: Map<string, { labels: Labels; counts: number[]; sum: number; count: number }>;
}

const counters = new Map<string, CounterState>();
const histograms = new Map<string, HistogramState>();

/** Stable key for a label set, so ordering does not create duplicate series. */
function labelKey(labels: Labels): string {
  return Object.keys(labels)
    .sort()
    .map((k) => `${k}=${labels[k]}`)
    .join(',');
}

function escapeLabel(value: string): string {
  return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n');
}

function renderLabels(labels: Labels): string {
  const entries = Object.entries(labels);
  if (entries.length === 0) return '';
  return `{${entries.map(([k, v]) => `${k}="${escapeLabel(v)}"`).join(',')}}`;
}

export function defineCounter(
  name: string,
  help: string,
  type: 'counter' | 'gauge' = 'counter',
): void {
  if (!counters.has(name)) counters.set(name, { help, type, values: new Map() });
}

export function increment(name: string, labels: Labels = {}, by = 1): void {
  const counter = counters.get(name);
  if (!counter) return;
  const key = labelKey(labels);
  const existing = counter.values.get(key);
  if (existing) existing.value += by;
  else counter.values.set(key, { labels, value: by });
}

export function setGauge(name: string, value: number, labels: Labels = {}): void {
  const counter = counters.get(name);
  if (!counter) return;
  counter.values.set(labelKey(labels), { labels, value });
}

export function defineHistogram(name: string, help: string, buckets: number[]): void {
  if (!histograms.has(name)) {
    histograms.set(name, { help, buckets: [...buckets].sort((a, b) => a - b), series: new Map() });
  }
}

export function observe(name: string, value: number, labels: Labels = {}): void {
  const histogram = histograms.get(name);
  if (!histogram) return;

  const key = labelKey(labels);
  let series = histogram.series.get(key);
  if (!series) {
    series = { labels, counts: new Array(histogram.buckets.length).fill(0), sum: 0, count: 0 };
    histogram.series.set(key, series);
  }

  series.sum += value;
  series.count += 1;
  // Cumulative buckets: Prometheus histograms are "less than or equal to".
  for (let i = 0; i < histogram.buckets.length; i++) {
    if (value <= histogram.buckets[i]!) series.counts[i] = (series.counts[i] ?? 0) + 1;
  }
}

