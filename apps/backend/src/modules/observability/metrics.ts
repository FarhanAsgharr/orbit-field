/**
 * Refresh gauges that describe fleet state.
 *
 * Queried at scrape time rather than maintained incrementally: these are
 * derived from the database, and a counter kept in process memory would be
 * wrong the moment a second replica exists.
 */
async function refreshGauges(): Promise<void> {
  try {
    const [conflicts, uploads, deviceRows] = await Promise.all([
      prisma.syncConflictRecord.count({ where: { resolvedAt: null } }),
      prisma.attachment.count({
        where: { deletedAt: null, state: { in: ['QUEUED', 'UPLOADING', 'FAILED'] } },
      }),
      prisma.$queryRaw<Array<{ behind: bigint; stale: bigint }>>`
        SELECT
          COUNT(*) FILTER (WHERE d."lastSyncCursor" < o."syncSequence")::bigint AS behind,
          COUNT(*) FILTER (WHERE d."lastSyncAt" IS NULL OR d."lastSyncAt" < NOW() - INTERVAL '24 hours')::bigint AS stale
        FROM devices d
        JOIN organizations o ON o.id = d."orgId"
        WHERE d."deletedAt" IS NULL AND d."revokedAt" IS NULL
      `,
    ]);

    setGauge('orbit_unresolved_conflicts', conflicts);
    setGauge('orbit_pending_uploads', uploads);
    setGauge('orbit_devices_behind', Number(deviceRows[0]?.behind ?? 0));
    setGauge('orbit_devices_stale', Number(deviceRows[0]?.stale ?? 0));
    setGauge('orbit_db_up', 1);
  } catch {
    // A scrape must always return something. Reporting the database as down is
    // more useful than a 500 that Prometheus records as a scrape failure with
    // no detail.
    setGauge('orbit_db_up', 0);
  }
}

/** Render the exposition format. */
export async function collectMetrics(): Promise<string> {
  await refreshGauges();

  const lines: string[] = [];

  for (const [name, counter] of counters) {
    lines.push(`# HELP ${name} ${counter.help}`);
    lines.push(`# TYPE ${name} ${counter.type}`);
    if (counter.values.size === 0) {
      lines.push(`${name} 0`);
      continue;
    }
    for (const { labels, value } of counter.values.values()) {
      lines.push(`${name}${renderLabels(labels)} ${value}`);
    }
  }

  for (const [name, histogram] of histograms) {
    lines.push(`# HELP ${name} ${histogram.help}`);
    lines.push(`# TYPE ${name} histogram`);
    for (const series of histogram.series.values()) {
      histogram.buckets.forEach((bucket, i) => {
        lines.push(
          `${name}_bucket${renderLabels({ ...series.labels, le: String(bucket) })} ${series.counts[i] ?? 0}`,
        );
      });
      lines.push(`${name}_bucket${renderLabels({ ...series.labels, le: '+Inf' })} ${series.count}`);
      lines.push(`${name}_sum${renderLabels(series.labels)} ${series.sum}`);
      lines.push(`${name}_count${renderLabels(series.labels)} ${series.count}`);
    }
  }

  // Process metrics an operator expects to find without a second exporter.
  const memory = process.memoryUsage();
  lines.push('# HELP orbit_process_resident_memory_bytes Resident memory.');
  lines.push('# TYPE orbit_process_resident_memory_bytes gauge');
  lines.push(`orbit_process_resident_memory_bytes ${memory.rss}`);
  lines.push('# HELP orbit_process_heap_used_bytes Heap in use.');
  lines.push('# TYPE orbit_process_heap_used_bytes gauge');
  lines.push(`orbit_process_heap_used_bytes ${memory.heapUsed}`);
  lines.push('# HELP orbit_process_uptime_seconds Seconds since start.');
  lines.push('# TYPE orbit_process_uptime_seconds gauge');
  lines.push(`orbit_process_uptime_seconds ${Math.floor(process.uptime())}`);

  return `${lines.join('\n')}\n`;
}

/**
 * Normalise a path into a route label.
 *
 * Raw paths would create one series per inspection id, which is how a metrics
 * backend runs out of memory. Identifiers collapse to `:id`.
 */
export function routeLabel(path: string): string {
  return path
    .replace(/\/[0-9A-HJKMNP-TV-Z]{26}(?=\/|$)/g, '/:id')
    .replace(/\/\d+(?=\/|$)/g, '/:n')
    .slice(0, 80);
}

export function resetMetrics(): void {
  for (const counter of counters.values()) counter.values.clear();
  for (const histogram of histograms.values()) histogram.series.clear();
}
